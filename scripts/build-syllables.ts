/**
 * Derives the inventory of valid toneless pinyin syllables from the
 * pinyin-pro package's dictionary (instead of typing the list by hand).
 * Output: src/lib/syllables.generated.ts. Re-run with `npm run syllables:build`.
 */
import { polyphonic } from 'pinyin-pro';
import { writeFileSync } from 'node:fs';

const found = new Set<string>();
const CHUNK = 2000;
for (let start = 0x4e00; start <= 0x9fff; start += CHUNK) {
  let text = '';
  for (let cp = start; cp < Math.min(start + CHUNK, 0xa000); cp++) text += String.fromCodePoint(cp);
  const readings = polyphonic(text, { toneType: 'none', type: 'array', v: true }) as string[][];
  for (const list of readings) {
    for (const r of list) {
      const s = r.toLowerCase().trim();
      if (/^[a-z]+$/.test(s)) found.add(s);
    }
  }
}
// Drop interjection-only forms without a vowel (m, n, ng, hm, hng).
const list = [...found].filter((s) => /[aeiouv]/.test(s)).sort();
const out =
  '// GENERATED by scripts/build-syllables.ts from pinyin-pro data. Do not edit by hand.\n' +
  `export const SYLLABLES: ReadonlySet<string> = new Set(${JSON.stringify(list.join(' '))}.split(' '));\n`;
writeFileSync('src/lib/syllables.generated.ts', out);
console.log(`Wrote ${list.length} syllables`);
